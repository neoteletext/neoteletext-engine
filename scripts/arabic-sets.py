"""Lays out the Arabic-script sets of group 1001 and writes their tables
into `crates/neoteletext-core/src/charset/tables.rs`: the eight code
tables, the joining type of every letter and the code point drawn for each
joined form (decision E.79, REQ-CHR-013 and REQ-CHR-015,
`docs/spec/design/languages.md` sections 6 and 8.3).

    uv run scripts/arabic-sets.py

Each table: Table 44's punctuation in columns 2 and 3, with guillemets at
2/6 and 2/7 in place of its presentation-form fragments and no mirroring;
the language's digits at 3/0 to 3/9; the letters in alphabet order from
4/0, then lam-alef (U+FEFB) and tatweel; spaces to 7/E; 7/F the block.

Joining types come from Unicode's ArabicShaping.txt, downloaded once to a
cache outside the repository and checked against its SHA-256. A joined form
is drawn from its Arabic Presentation Form where Unicode has one, otherwise
from a private-use code point allocated in order from U+F0000.

The script replaces the text between the two marker lines in tables.rs and
nothing else. Run `cargo xtask glyphs` afterwards to rewrite `forms.txt` and
`required.txt`, then `third_party/noto/convert.py` to redraw the fonts.
"""

import hashlib
import sys
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "crates/neoteletext-core/src/charset/tables.rs"
BEGIN = "// BEGIN generated by scripts/arabic-sets.py: edit the script, not this.\n"
END = "// END generated by scripts/arabic-sets.py.\n"

SHAPING_URL = "https://www.unicode.org/Public/16.0.0/ucd/ArabicShaping.txt"
SHAPING_SHA256 = "764f420cedfc8b43d9fec251c957a5d55fc45d40f6573f162990ed1dce7e36e0"
CACHE = Path.home() / ".cache" / "neoteletext" / "ArabicShaping-16.0.0.txt"

EXTENDED_DIGITS = "".join(chr(0x06F0 + i) for i in range(10))
ARABIC_DIGITS = "".join(chr(0x0660 + i) for i in range(10))
WESTERN_DIGITS = "0123456789"
# Name, Table 33 option bits, letters in alphabet order, digits, full stop.
SETS = [
    ("Persian", "000", "ءآأؤإئابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهیۀة", EXTENDED_DIGITS, "."),
    ("Urdu", "001", "ءآأؤئابپتٹثجچحخدڈذرڑزژسشصضطظعغفقکگلمنںوہھیےۂۓ", EXTENDED_DIGITS, "۔"),
    ("Pashto", "010", "ءآأؤئابپتټثجځچڅحخدډذرړزژږسشښصضطظعغفقکګلمنڼوهیۍېيۀة", EXTENDED_DIGITS, "."),
    ("Sindhi", "011", "ءآأؤئابٻڀتٿٽٺثپجڄڃچڇحخدڌڏڊڍذرڙزژسشصضطظعغفڦقڪکڳگڱلمنڻوهھي۽", EXTENDED_DIGITS, "."),
    ("Sorani", "100", "ءئابپتجچحخدرڕزژسشعغفڤقکگلڵمنهەوۆیێھ", ARABIC_DIGITS, "."),
    ("Uyghur", "101", "ئاەبپتجچخدرزژسشغفقكگڭلمنھوۇۆۈۋېىي", WESTERN_DIGITS, "."),
    # ۏ after و and ࢩ after ی, as Google Fonts' language data lists them.
    ("Balochi", "110", "ءآئابپتٹثجچحخدڈذرڑزژسشصضطظعغفقکگلمنوۏهھیࢩے", EXTENDED_DIGITS, "."),
    ("ArabicPlain", "111", "ءآأؤإئابةتثجحخدذرزسشصضطظعغفقكلمنهوىي", ARABIC_DIGITS, "."),
]
LAM_ALEF = "ﻻ"
LAM_ALEF_FINAL = "ﻼ"
TATWEEL = "ـ"
BLOCK = "■"
PRIVATE_FORMS_START = 0xF0000
CODES = 96
LETTER_CODES = 63  # 4/0 to 7/E
FORMS = ["final", "initial", "medial"]
WANTED_FORMS = {"D": FORMS, "R": ["final"], "C": [], "U": []}
TYPE_NAMES = {"D": "Dual", "R": "Right", "U": "None", "C": "Causing"}


def shaping_text():
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(SHAPING_URL) as response:
            CACHE.write_bytes(response.read())
    data = CACHE.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHAPING_SHA256:
        sys.exit(f"{CACHE}: SHA-256 differs from {SHAPING_SHA256}")
    return data.decode()


def joining_types():
    types = {}
    for line in shaping_text().splitlines():
        if line and line[0] in "0123456789ABCDEF":
            code, _name, kind, _group = (part.strip() for part in line.split(";"))
            types[chr(int(code, 16))] = kind
    types[LAM_ALEF] = "R"
    return types


def presentation_forms():
    forms = {}
    for code in [*range(0xFB50, 0xFE00), *range(0xFE70, 0xFF00)]:
        decomposition = unicodedata.decomposition(chr(code))
        if not decomposition.startswith("<"):
            continue
        tag, *parts = decomposition.split()
        base = "".join(chr(int(part, 16)) for part in parts)
        forms.setdefault((base, tag[1:-1]), chr(code))
    forms[(LAM_ALEF, "final")] = LAM_ALEF_FINAL
    return forms


def code_table(letters, digits, stop):
    cells = [" ", "!", '"', "#", "$", "%", "«", "»", "(", ")", "*", "+", "،", "-", stop, "/"]
    cells += [*digits, ":", "؛", "<", "=", ">", "؟"]
    rest = [*letters, LAM_ALEF, TATWEEL]
    if len(rest) > LETTER_CODES:
        sys.exit(f"{len(rest)} letters do not fit in {LETTER_CODES} codes")
    cells += rest + [" "] * (LETTER_CODES - len(rest)) + [BLOCK]
    assert len(cells) == CODES
    return cells


def literal(character):
    return f"'\\u{{{ord(character):04X}}}'"


def generated():
    shaping = joining_types()
    forms = presentation_forms()
    out = []
    types = {}
    for name, option, letters, digits, stop in SETS:
        if len(set(letters)) != len(letters):
            sys.exit(f"{name}: a letter is listed twice")
        cells = code_table(letters, digits, stop)
        for letter in [*letters, LAM_ALEF]:
            kind = shaping.get(letter, "U")
            assert kind in "DRUC", (name, letter, kind)
            types[letter] = kind
        out.append(f"/// Group 1001 option {option}: `{name}` (REQ-CHR-013, `docs/spec/design/languages.md` section 8.3).")
        out.append(f"const {name.upper()}_G0: CodeTable = [")
        for row in range(CODES // 16):
            out.append("    " + ", ".join(literal(c) for c in cells[row * 16 : (row + 1) * 16]) + ", //")
        out.append("];")
        out.append("")
    private = PRIVATE_FORMS_START
    form_rows = []
    for letter in sorted(types):
        for form in WANTED_FORMS[types[letter]]:
            point = forms.get((letter, form))
            if point is None:
                point = chr(private)
                private += 1
            form_rows.append((letter, form, point))
    out.append("/// Each joining letter of group 1001 and its joining type (Unicode")
    out.append("/// `ArabicShaping.txt`, 16.0), sorted by letter for binary search.")
    out.append(f"const JOINING_TYPES: [(char, JoiningType); {len(types)}] = [")
    for letter in sorted(types):
        out.append(f"    ({literal(letter)}, JoiningType::{TYPE_NAMES[types[letter]]}), // {unicodedata.name(letter)}")
    out.append("];")
    out.append("")
    out.append("/// The code point drawn for each joined form: an Arabic Presentation")
    out.append("/// Form, or the core's own in Supplementary Private Use Area-A from")
    out.append("/// U+F0000 where Unicode has none (REQ-CHR-015). Sorted by letter, then")
    out.append("/// form.")
    out.append(f"pub(super) const JOINED_FORMS: [(char, JoinForm, char); {len(form_rows)}] = [")
    for letter, form, point in sorted(form_rows, key=lambda row: (row[0], FORMS.index(row[1]))):
        out.append(f"    ({literal(letter)}, JoinForm::{form.capitalize()}, {literal(point)}),")
    out.append("];")
    print(f"{len(types)} joining letters, {len(form_rows)} forms, {private - PRIVATE_FORMS_START} private", file=sys.stderr)
    return "\n".join(out) + "\n"


def main():
    text = TABLES.read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        sys.exit(f"{TABLES}: expected one each of the marker lines")
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    TABLES.write_text(head + BEGIN + generated() + END + tail)


if __name__ == "__main__":
    main()
