def epic(key, title, labels, milestone, goal, prior_art, security, constraints, sources, tasks):
    EPICS.append(dict(key=key, title=title, labels=labels, milestone=milestone, goal=goal,
                      prior_art=prior_art, security=security, constraints=constraints,
                      sources=sources, tasks=tasks))


def t(title, desc, done, sec=None, milestone=None, labels=()):
    return dict(title=title, desc=desc, done=done, sec=sec, milestone=milestone, labels=list(labels))


