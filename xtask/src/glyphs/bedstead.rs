//! The Bedstead glyph table, generated from the bundled export, and the
//! export's check against its provenance record (REQ-FNT-001, REQ-RND-020).

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

pub(super) const SOURCE: &str = "third_party/bedstead/bedstead-glyphs.txt";
pub(super) const TARGET: &str = "crates/neoteletext-core/src/glyphs/bedstead.rs";
const PROVENANCE: &str = "third_party/bedstead/PROVENANCE.md";
/// The line of the provenance record that gives the export's checksum.
const CHECKSUM_PREFIX: &str = "**Export SHA-256:** `";
/// Glyph rows per entry (REQ-RND-010).
const GLYPH_LINES: usize = 9;

struct Entry {
    code_point: u32,
    rows: [u8; GLYPH_LINES],
}

fn parse(line: &str, number: usize) -> Result<Entry, String> {
    let mut fields = line.split_whitespace();
    let code = fields.next().ok_or(format!("line {number}: empty"))?;
    let hex = code.strip_prefix("U+").ok_or(format!("line {number}: no U+ prefix"))?;
    let code_point = u32::from_str_radix(hex, 16).map_err(|e| format!("line {number}: {e}"))?;
    let _name = fields.next().ok_or(format!("line {number}: no name"))?;
    let mut rows = [0u8; GLYPH_LINES];
    for row in &mut rows {
        let value = fields.next().ok_or(format!("line {number}: too few rows"))?;
        *row = u8::from_str_radix(value, 16).map_err(|e| format!("line {number}: {e}"))?;
        if *row > 0x1F {
            return Err(format!("line {number}: row wider than five dots"));
        }
    }
    if fields.next().is_some() {
        return Err(format!("line {number}: too many fields"));
    }
    Ok(Entry { code_point, rows })
}

/// The Rust source of the Bedstead glyph table.
pub(super) fn bedstead_source(text: &str) -> Result<(String, usize), String> {
    let mut entries = Vec::new();
    for (index, line) in text.lines().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        entries.push(parse(line, index + 1)?);
    }
    entries.sort_by_key(|entry| entry.code_point);
    entries.dedup_by_key(|entry| entry.code_point);
    let mut out = String::new();
    out.push_str("//! Generated by `cargo xtask glyphs` from third_party/bedstead/bedstead-glyphs.txt.\n");
    out.push_str("//! Do not edit by hand.\n\nuse super::GlyphEntry;\n\n");
    out.push_str("/// Where these glyphs come from (REQ-GEN-012, REQ-FNT-001).\n");
    out.push_str("pub(super) const PROVENANCE: &str = \"Bedstead 3.261, the bundled font (see third_party/bedstead/PROVENANCE.md)\";\n\n");
    let _ = writeln!(out, "pub(super) static GLYPHS: [GlyphEntry; {}] = [", entries.len());
    for entry in &entries {
        let rows: Vec<String> = entry.rows.iter().map(|row| format!("0x{row:02X}")).collect();
        let _ =
            writeln!(out, "    GlyphEntry {{ code_point: 0x{:04X}, rows: [{}] }},", entry.code_point, rows.join(", "));
    }
    out.push_str("];\n");
    Ok((out, entries.len()))
}

/// `cargo xtask check-bedstead`: the export is the file its provenance
/// record names, by SHA-256 (REQ-FNT-001).
pub fn check_bedstead(root: &Path) -> Result<(), String> {
    let export = fs::read(root.join(SOURCE)).map_err(|e| format!("{SOURCE}: {e}"))?;
    let record = fs::read_to_string(root.join(PROVENANCE)).map_err(|e| format!("{PROVENANCE}: {e}"))?;
    let recorded = recorded_checksum(&record).ok_or(format!("{PROVENANCE} has no line starting {CHECKSUM_PREFIX}"))?;
    let actual = neoteletext_web::sha256::to_hex(&neoteletext_web::sha256::digest(&export));
    if recorded.as_bytes() != actual {
        return Err(format!(
            "{SOURCE} has SHA-256 {}, but {PROVENANCE} records {recorded}",
            String::from_utf8_lossy(&actual)
        ));
    }
    println!("{SOURCE}: SHA-256 matches {PROVENANCE}");
    Ok(())
}

/// The checksum the provenance record gives, from its one checksum line.
pub(super) fn recorded_checksum(record: &str) -> Option<&str> {
    let mut lines = record.lines().filter_map(|line| line.strip_prefix(CHECKSUM_PREFIX));
    let rest = lines.next()?;
    if lines.next().is_some() {
        return None;
    }
    rest.split('`').next()
}
