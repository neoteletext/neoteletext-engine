//! The core's G3 table, generated from the text the G3 geometry writes
//! (REQ-RND-037, decision E.50).

use crate::g3;
use std::fmt::Write as _;

pub(super) const G3_TEXT: &str = "crates/neoteletext-core/src/glyphs/g3.txt";
pub(super) const G3_TARGET: &str = "crates/neoteletext-core/src/glyphs/g3.rs";

/// The Rust source of the G3 table, from the text form of [`g3::text`]:
/// every position must appear once at each height, in order.
pub(super) fn g3_source(text: &str) -> Result<String, String> {
    let mut glyphs: Vec<[Vec<u16>; 2]> = vec![[Vec::new(), Vec::new()]; g3::CODES];
    for (index, line) in text.lines().enumerate() {
        let number = index + 1;
        if line.starts_with('#') || line.trim().is_empty() {
            continue;
        }
        let mut fields = line.split_whitespace();
        let position = fields.next().ok_or(format!("line {number}: empty"))?;
        let (column, row) = position.split_once('/').ok_or(format!("line {number}: bad position"))?;
        let code = u8::from_str_radix(&format!("{column}{row}"), 16).map_err(|e| format!("line {number}: {e}"))?;
        let offset = usize::from(code.checked_sub(g3::FIRST_CODE).ok_or(format!("line {number}: code below 2/0"))?);
        let height: usize = fields
            .next()
            .ok_or(format!("line {number}: no height"))?
            .parse()
            .map_err(|e| format!("line {number}: {e}"))?;
        let slot = g3::HEIGHTS.iter().position(|&h| h == height).ok_or(format!("line {number}: height {height}"))?;
        let lines: Vec<u16> = fields
            .map(|value| u16::from_str_radix(value, 16).map_err(|e| format!("line {number}: {e}")))
            .collect::<Result<_, _>>()?;
        if lines.len() != height || lines.iter().any(|&line| line >> g3::CELL_WIDTH != 0) {
            return Err(format!("line {number}: expected {height} lines of 12 bits"));
        }
        let target = glyphs.get_mut(offset).ok_or(format!("line {number}: code above 7/F"))?;
        if !target[slot].is_empty() {
            return Err(format!("line {number}: {position} at height {height} twice"));
        }
        target[slot] = lines;
    }
    let mut out = String::new();
    out.push_str("//! Generated by `cargo xtask glyphs` from g3.txt, which the same command\n");
    out.push_str("//! draws from the project's own geometry (decision E.50). Do not edit by hand.\n\n");
    out.push_str("use super::G3Glyph;\n\n");
    out.push_str("/// Where these glyphs come from (REQ-GEN-012, REQ-RND-037).\n");
    out.push_str("pub(super) const PROVENANCE: &str = \"neoteletext G3 geometry (decision E.50; generated by cargo xtask glyphs, see g3.txt)\";\n\n");
    let _ = writeln!(out, "pub(super) static G3: [G3Glyph; {}] = [", g3::CODES);
    for (offset, [small, large]) in glyphs.iter().enumerate() {
        if small.is_empty() || large.is_empty() {
            return Err(format!("position {:#04X} is missing a height", usize::from(g3::FIRST_CODE) + offset));
        }
        let hex = |lines: &[u16]| lines.iter().map(|line| format!("0x{line:04X}")).collect::<Vec<_>>().join(", ");
        let _ = writeln!(out, "    G3Glyph {{");
        let _ = writeln!(out, "        small: [{}],", hex(small));
        let _ = writeln!(out, "        large: [{}],", hex(large));
        let _ = writeln!(out, "    }},");
    }
    out.push_str("];\n");
    Ok(out)
}
