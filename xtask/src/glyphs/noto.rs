//! The core's compiled font (REQ-FNT-001, decision E.77 as amended by
//! DEC-1761), generated from the Noto Teletext BDF files by the engine's own
//! bounded reader.

use super::required::standard_characters;
use neoteletext_core::consts::{CELL_HEIGHT, FONT_MAX_CHARACTERS};
use neoteletext_core::types::FontGlyph;
use neoteletext_formats::bdf;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// The Noto Teletext files. The font is spread over them because a font file
/// holds at most [`FONT_MAX_CHARACTERS`] characters (REQ-FNT-002), and
/// together they are the one font.
pub(super) const SOURCES: [&str; 4] = [
    "third_party/noto/noto-teletext.bdf",
    "third_party/noto/noto-teletext-composed.bdf",
    "third_party/noto/noto-teletext-arabic.bdf",
    "third_party/noto/noto-teletext-thai.bdf",
];
pub(super) const TARGET: &str = "crates/neoteletext-core/src/glyphs/noto.rs";

/// The glyphs of one file, as the engine reads a loaded font.
fn read(path: &str, bytes: &[u8]) -> Result<Vec<FontGlyph>, String> {
    let mut table = vec![FontGlyph::EMPTY; FONT_MAX_CHARACTERS];
    let font = bdf::read(bytes, &mut table).map_err(|error| format!("{path}: {error:?}"))?;
    table.truncate(font.characters);
    Ok(table)
}

/// The files merged by code point. Two files may hold a character only if
/// they agree on it, since a character has one shape in the one font.
fn merged(files: &[(&str, Vec<u8>)]) -> Result<BTreeMap<u32, [u16; CELL_HEIGHT]>, String> {
    let mut glyphs = BTreeMap::new();
    for (path, bytes) in files {
        for glyph in read(path, bytes)? {
            if !glyph.tall {
                return Err(format!("{path}: U+{:04X} is not 12 by 20", glyph.code_point));
            }
            let first = glyphs.entry(glyph.code_point).or_insert(glyph.rows);
            if *first != glyph.rows {
                return Err(format!("{path}: U+{:04X} differs from an earlier file's", glyph.code_point));
            }
        }
    }
    Ok(glyphs)
}

/// One table of the generated file.
fn write_table<'a>(out: &mut String, name: &str, glyphs: impl ExactSizeIterator<Item = (&'a u32, &'a [u16; 20])>) {
    let _ = writeln!(out, "pub(super) static {name}: [GlyphEntry; {}] = [", glyphs.len());
    for (code_point, rows) in glyphs {
        let rows: Vec<String> = rows.iter().map(|row| format!("0x{row:03X}")).collect();
        let _ = writeln!(out, "    GlyphEntry {{ code_point: 0x{code_point:04X}, rows: [{}] }},", rows.join(", "));
    }
    out.push_str("];\n");
}

/// The Rust source of the compiled font, and how many glyphs it holds.
pub(super) fn noto_source(files: &[(&str, Vec<u8>)]) -> Result<(String, usize), String> {
    let glyphs = merged(files)?;
    let standard: BTreeSet<u32> = standard_characters().into_iter().map(u32::from).collect();
    let (first, extended): (BTreeMap<u32, _>, BTreeMap<u32, _>) =
        glyphs.iter().map(|(&code_point, &rows)| (code_point, rows)).partition(|(code, _)| standard.contains(code));
    if let Some(lacking) = standard.iter().find(|code| !first.contains_key(code)) {
        return Err(format!("the Noto Teletext files have no U+{lacking:04X}, which the standard's sets need"));
    }
    let mut out = String::new();
    out.push_str("//! Generated by `cargo xtask glyphs` from `third_party/noto/*.bdf`.\n");
    out.push_str("//! Do not edit by hand.\n\nuse super::GlyphEntry;\n\n");
    out.push_str("/// Where these glyphs come from (REQ-GEN-012, REQ-FNT-001), and the notice the\n");
    out.push_str("/// SIL Open Font License 1.1 requires a copy of the font to carry.\n");
    out.push_str("pub(super) const PROVENANCE: &str = \"Noto Teletext, converted from Noto: Copyright 2022 The Noto Project Authors, ");
    out.push_str("SIL Open Font License 1.1 (see third_party/noto/OFL.txt and PROVENANCE.md)\";\n\n");
    out.push_str("/// The standard's sets, the spacing marks and the Latin compositions.\n");
    write_table(&mut out, "GLYPHS", first.iter());
    out.push_str(
        "\n/// The rest of the font: neoteletext's own sets (REQ-CHR-012).\n#[cfg(feature = \"extended-sets\")]\n",
    );
    write_table(&mut out, "EXTENDED_GLYPHS", extended.iter());
    out.push_str(
        "\n/// Without the feature no page can select those sets.\n#[cfg(not(feature = \"extended-sets\"))]\n",
    );
    out.push_str("pub(super) static EXTENDED_GLYPHS: [GlyphEntry; 0] = [];\n");
    Ok((out, glyphs.len()))
}

/// Every source file, read.
pub(super) fn source_files(root: &Path) -> Result<Vec<(&'static str, Vec<u8>)>, String> {
    SOURCES.iter().map(|&path| Ok((path, fs::read(root.join(path)).map_err(|e| format!("{path}: {e}"))?))).collect()
}
