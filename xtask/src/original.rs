//! The original glyph set's inventory and acceptance checks (REQ-RND-028,
//! decision E.62):
//!
//! - `cargo xtask glyph-inventory` writes the required characters, generated
//!   from the core's character set tables, to `required.txt`.
//! - `cargo xtask glyph-check [--complete]` checks `original.txt`: format,
//!   well-formedness, confusables, independence from the Bedstead glyphs
//!   (the stand-in for the SAA5050), and coverage, which `--complete`
//!   requires to be whole.
//! - `cargo xtask glyph-proof OUT.png [--compare] [TEXT...]` draws every
//!   glyph, each beside its Bedstead glyph with `--compare`, then each TEXT
//!   as a line, for review by people (decision E.62).
//!
//! The file format and the drawing rules are in `docs/glyph-style-guide.md`.

use neoteletext_core::charset::{CharRef, CharSet, G0, G0Set, G2Set, NationalOption, to_unicode};
use neoteletext_core::glyphs::{PLACEHOLDER, SPACING_MARKS};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const REQUIRED: &str = "crates/neoteletext-core/src/glyphs/required.txt";
const ORIGINAL: &str = "crates/neoteletext-core/src/glyphs/original.txt";
/// The generated table of the original glyphs.
pub const TABLE: &str = "crates/neoteletext-core/src/glyphs/original.rs";
const CONFUSABLES: &str = "crates/neoteletext-core/src/glyphs/confusables.txt";
const AUDIT: &str = "crates/neoteletext-core/src/glyphs/original-audit.txt";
const BEDSTEAD: &str = "third_party/bedstead/bedstead-glyphs.txt";
const CORE_MANIFEST: &str = "crates/neoteletext-core/Cargo.toml";

/// The glyph grid (REQ-RND-010).
const COLUMNS: usize = 5;
const ROWS: usize = 9;
/// The descender rows (style guide): ink here needs the `descender` tag.
const DESCENDER_ROWS: [usize; 2] = [7, 8];
/// The baseline row: a letter's lowest stroke above the descenders.
const BASELINE_ROW: usize = 6;
/// Characters 2/0 to 7/F of a set (clause 15).
const FIRST_CODE: u8 = 0x20;
const LAST_CODE: u8 = 0x7F;
/// Glyphs closer than this many dots to a confusable partner fail.
const CONFUSABLE_DISTANCE: u32 = 2;
/// A drawn glyph this close to the Bedstead glyph needs an audit reason.
const AUDIT_DISTANCE: u32 = 1;
/// Characters whose glyph may be empty.
const BLANK: [char; 2] = [' ', '\u{00A0}'];

type Rows = [u8; ROWS];

/// One character set the renderer can show, with its characters.
struct Set {
    name: String,
    characters: Vec<(u8, char)>,
}

/// Every G0 set, with each national option of the Latin set, and every G2
/// set.
fn sets() -> Vec<Set> {
    let mut g0: Vec<(String, CharSet)> =
        vec![("G0 Latin".to_string(), CharSet::G0(G0 { set: G0Set::Latin, national: None }))];
    for national in NationalOption::ALL {
        g0.push((format!("G0 Latin {national:?}"), CharSet::G0(G0 { set: G0Set::Latin, national: Some(national) })));
    }
    for set in [G0Set::Cyrillic1, G0Set::Cyrillic2, G0Set::Cyrillic3, G0Set::Greek, G0Set::Arabic, G0Set::Hebrew] {
        g0.push((format!("G0 {set:?}"), CharSet::G0(G0 { set, national: None })));
    }
    for set in [G2Set::Latin, G2Set::Cyrillic, G2Set::Greek, G2Set::Arabic] {
        g0.push((format!("G2 {set:?}"), CharSet::G2(set)));
    }
    g0.into_iter()
        .map(|(name, set)| Set {
            name,
            characters: (FIRST_CODE..=LAST_CODE)
                .map(|code| (code, to_unicode(CharRef::new(set, code)).base))
                .filter(|(_, c)| !c.is_control())
                .collect(),
        })
        .collect()
}

/// The required characters and where each is used.
fn required() -> BTreeMap<char, Vec<String>> {
    let mut out: BTreeMap<char, Vec<String>> = BTreeMap::new();
    for set in sets() {
        for (code, character) in &set.characters {
            out.entry(*character).or_default().push(format!("{} {}/{:X}", set.name, code >> 4, code & 0xF));
        }
    }
    for (_, spacing) in SPACING_MARKS {
        out.entry(spacing).or_default().push("spacing mark (decision E.26)".to_string());
    }
    out
}

fn required_text() -> String {
    let mut text = String::from(
        "; Generated by `cargo xtask glyph-inventory` (decision E.62). Do not edit.\n\
         ; Every character a glyph set must draw: code point, character, where it is used.\n",
    );
    for (character, uses) in required() {
        let shown = if character == ' ' { "SPACE".to_string() } else { character.to_string() };
        let _ = writeln!(text, "U+{:04X} {shown} {}", u32::from(character), uses.join("; "));
    }
    text
}

/// `cargo xtask glyph-inventory`.
pub fn inventory(root: &Path) -> Result<(), String> {
    let text = required_text();
    fs::write(root.join(REQUIRED), &text).map_err(|e| format!("{REQUIRED}: {e}"))?;
    println!("{REQUIRED}: {} characters", text.lines().filter(|line| line.starts_with("U+")).count());
    Ok(())
}

/// One entry of `original.txt`.
#[derive(Clone)]
enum Entry {
    Drawn { rows: Rows, tags: BTreeSet<String> },
    Copy(char, BTreeSet<String>),
    Overlay(char, char, BTreeSet<String>),
}

fn code_point(field: &str, line: usize) -> Result<char, String> {
    let hex = field.strip_prefix("U+").ok_or(format!("line {line}: `{field}` is not U+XXXX"))?;
    let value = u32::from_str_radix(hex, 16).map_err(|e| format!("line {line}: {e}"))?;
    char::from_u32(value).ok_or(format!("line {line}: U+{hex} is not a character"))
}

/// The tags an entry may carry (style guide). They describe the glyph the
/// entry resolves to, so copies and overlays carry them too.
const TAGS: [&str; 3] = ["descender", "dots", "raised"];

fn tags_of(fields: &[&str], line: usize) -> Result<BTreeSet<String>, String> {
    fields
        .iter()
        .map(
            |tag| {
                if TAGS.contains(tag) {
                    Ok((*tag).to_string())
                } else {
                    Err(format!("line {line}: unknown tag `{tag}`"))
                }
            },
        )
        .collect()
}

fn parse_original(text: &str) -> Result<BTreeMap<char, Entry>, Vec<String>> {
    let mut entries = BTreeMap::new();
    let mut errors = Vec::new();
    let lines: Vec<(usize, &str)> =
        text.lines().enumerate().map(|(i, l)| (i + 1, l.trim_end())).filter(|(_, l)| !l.starts_with(';')).collect();
    let mut index = 0;
    while index < lines.len() {
        let (number, line) = lines[index];
        index += 1;
        if line.is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split_whitespace().collect();
        let character = match code_point(fields[0], number) {
            Ok(c) => c,
            Err(e) => {
                errors.push(e);
                continue;
            }
        };
        let entry = match fields.get(1).copied() {
            Some("drawn") => {
                let mut rows = [0u8; ROWS];
                let mut ok = true;
                for row in &mut rows {
                    let Some(&(row_number, text)) = lines.get(index) else {
                        errors
                            .push(format!("line {number}: U+{:04X} has fewer than {ROWS} rows", u32::from(character)));
                        ok = false;
                        break;
                    };
                    index += 1;
                    if text.len() != COLUMNS || !text.chars().all(|c| c == '#' || c == '.') {
                        errors.push(format!("line {row_number}: a row is {COLUMNS} of `#` and `.`, not `{text}`"));
                        ok = false;
                    }
                    *row = text.chars().fold(0u8, |acc, c| (acc << 1) | u8::from(c == '#'));
                }
                let tags = match tags_of(&fields[2..], number) {
                    Ok(tags) => tags,
                    Err(e) => {
                        errors.push(e);
                        continue;
                    }
                };
                if !ok {
                    continue;
                }
                Entry::Drawn { rows, tags }
            }
            Some("copy") if fields.len() >= 3 => match (code_point(fields[2], number), tags_of(&fields[3..], number)) {
                (Ok(source), Ok(tags)) => Entry::Copy(source, tags),
                (Err(e), _) | (_, Err(e)) => {
                    errors.push(e);
                    continue;
                }
            },
            Some("overlay") if fields.len() >= 4 => {
                match (code_point(fields[2], number), code_point(fields[3], number), tags_of(&fields[4..], number)) {
                    (Ok(base), Ok(mark), Ok(tags)) => Entry::Overlay(base, mark, tags),
                    (Err(e), _, _) | (_, Err(e), _) | (_, _, Err(e)) => {
                        errors.push(e);
                        continue;
                    }
                }
            }
            _ => {
                errors.push(format!(
                    "line {number}: expected `U+XXXX drawn [tags]`, `copy U+XXXX [tags]` or `overlay U+XXXX U+XXXX [tags]`"
                ));
                continue;
            }
        };
        if entries.insert(character, entry).is_some() {
            errors.push(format!("line {number}: U+{:04X} appears twice", u32::from(character)));
        }
    }
    if errors.is_empty() { Ok(entries) } else { Err(errors) }
}

/// The glyph of an entry, following copies and overlays.
fn resolve(entries: &BTreeMap<char, Entry>, character: char, depth: usize) -> Option<Rows> {
    if depth > entries.len() {
        return None;
    }
    match entries.get(&character)? {
        Entry::Drawn { rows, .. } => Some(*rows),
        Entry::Copy(source, _) => resolve(entries, *source, depth + 1),
        Entry::Overlay(base, mark, _) => {
            let base = resolve(entries, *base, depth + 1)?;
            let mark = resolve(entries, *mark, depth + 1)?;
            let mut out = base;
            for (row, m) in out.iter_mut().zip(mark) {
                *row |= m;
            }
            Some(out)
        }
    }
}

fn distance(a: &Rows, b: &Rows) -> u32 {
    a.iter().zip(b).map(|(x, y)| (x ^ y).count_ones()).sum()
}

fn ink(rows: &Rows, row: usize, column: usize) -> bool {
    rows[row] & (1 << (COLUMNS - 1 - column)) != 0
}

/// A dot with no neighbour, side by side or corner to corner.
fn has_isolated_dot(rows: &Rows) -> bool {
    (0..ROWS).any(|r| {
        (0..COLUMNS).any(|c| {
            ink(rows, r, c)
                && !(r.saturating_sub(1)..=(r + 1).min(ROWS - 1)).any(|nr| {
                    (c.saturating_sub(1)..=(c + 1).min(COLUMNS - 1)).any(|nc| (nr, nc) != (r, c) && ink(rows, nr, nc))
                })
        })
    })
}

/// The rules of the style guide that a program can check.
fn well_formed(character: char, rows: &Rows, tags: &BTreeSet<String>) -> Vec<String> {
    let name = format!("U+{:04X} {character}", u32::from(character));
    let mut problems = Vec::new();
    let descends = DESCENDER_ROWS.iter().any(|&r| rows[r] != 0);
    if descends != tags.contains("descender") {
        problems.push(if descends {
            format!("{name}: ink in rows 7 to 8 needs the `descender` tag")
        } else {
            format!("{name}: tagged `descender` but rows 7 to 8 are empty")
        });
    }
    if has_isolated_dot(rows) && !tags.contains("dots") {
        problems.push(format!("{name}: an isolated dot needs the `dots` tag"));
    }
    if rows.iter().all(|&r| r == 0) && !BLANK.contains(&character) {
        problems.push(format!("{name}: empty glyph"));
    }
    // Spacing marks are letters to Unicode (modifier letters) but sit above
    // or below the letter they mark.
    let mark = SPACING_MARKS.iter().any(|(_, spacing)| *spacing == character);
    if character.is_alphabetic() && !mark && rows[BASELINE_ROW] == 0 && !descends && !tags.contains("raised") {
        problems.push(format!("{name}: a letter stands on the baseline (row 6), or is tagged `raised`"));
    }
    problems
}

/// Pairs of code points that must differ by at least
/// [`CONFUSABLE_DISTANCE`] dots.
fn confusable_pairs(text: &str) -> Result<Vec<(char, char)>, String> {
    let mut pairs = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let line = line.split(';').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let fields: Vec<&str> = line.split_whitespace().collect();
        let [a, b] = fields.as_slice() else {
            return Err(format!("{CONFUSABLES} line {}: two code points", index + 1));
        };
        pairs.push((code_point(a, index + 1)?, code_point(b, index + 1)?));
    }
    Ok(pairs)
}

/// Code points the audit file justifies, with the reason.
fn audit_reasons(text: &str) -> Result<BTreeMap<char, String>, String> {
    let mut out = BTreeMap::new();
    for (index, line) in text.lines().enumerate() {
        if line.trim().is_empty() || line.starts_with(';') {
            continue;
        }
        let (code, reason) = line.split_once(' ').ok_or(format!("{AUDIT} line {}: `U+XXXX reason`", index + 1))?;
        if reason.trim().is_empty() {
            return Err(format!("{AUDIT} line {}: a reason is required", index + 1));
        }
        out.insert(code_point(code, index + 1)?, reason.trim().to_string());
    }
    Ok(out)
}

fn bedstead(root: &Path) -> Result<BTreeMap<char, Rows>, String> {
    let text = fs::read_to_string(root.join(BEDSTEAD)).map_err(|e| format!("{BEDSTEAD}: {e}"))?;
    let mut out = BTreeMap::new();
    for line in text.lines() {
        let mut fields = line.split_whitespace();
        let (Some(code), Some(_name)) = (fields.next(), fields.next()) else { continue };
        let Ok(character) = code_point(code, 0) else { continue };
        let mut rows = [0u8; ROWS];
        for row in &mut rows {
            *row = fields.next().and_then(|v| u8::from_str_radix(v, 16).ok()).unwrap_or(0);
        }
        out.insert(character, rows);
    }
    Ok(out)
}

fn read(root: &Path, path: &str) -> Result<String, String> {
    fs::read_to_string(root.join(path)).map_err(|e| format!("{path}: {e}"))
}

/// REQ-RND-020: a release build draws no Bedstead glyph, so the core's
/// default features must include the original set and not the Bedstead set.
fn release_defaults(root: &Path) -> Result<Option<String>, String> {
    let manifest = read(root, CORE_MANIFEST)?;
    let defaults = manifest.lines().find(|line| line.starts_with("default =")).unwrap_or_default();
    Ok((defaults.contains("\"bedstead\"") || !defaults.contains("\"original\""))
        .then(|| format!("{CORE_MANIFEST}: the default features must include `original` and not `bedstead`")))
}

/// `cargo xtask glyph-check [--complete]`.
pub fn check(root: &Path, args: &[String]) -> Result<(), String> {
    let complete = match args {
        [] => false,
        [flag] if flag == "--complete" => true,
        _ => return Err("usage: cargo xtask glyph-check [--complete]".into()),
    };
    if read(root, REQUIRED)? != required_text() {
        return Err(format!("{REQUIRED} is out of date: run `cargo xtask glyph-inventory`"));
    }
    let entries = parse_original(&read(root, ORIGINAL)?).map_err(|errors| errors.join("\n"))?;
    let confusables = confusable_pairs(&read(root, CONFUSABLES)?)?;
    let reasons = audit_reasons(&read(root, AUDIT)?)?;
    let reference = bedstead(root)?;
    let mut failures = Vec::new();

    // Every entry resolves, and copies and overlays name real entries.
    let mut glyphs = BTreeMap::new();
    for &character in entries.keys() {
        match resolve(&entries, character, 0) {
            Some(rows) => {
                glyphs.insert(character, rows);
            }
            None => failures.push(format!("U+{:04X}: refers to a missing entry, or to itself", u32::from(character))),
        }
    }
    // Well-formedness of every glyph, against its entry's tags.
    for (character, entry) in &entries {
        let tags = match entry {
            Entry::Drawn { tags, .. } | Entry::Copy(_, tags) | Entry::Overlay(_, _, tags) => tags,
        };
        if let Some(rows) = glyphs.get(character) {
            failures.extend(well_formed(*character, rows, tags));
        }
    }
    // No two characters of one set share a glyph.
    for set in sets() {
        let mut seen: BTreeMap<Rows, char> = BTreeMap::new();
        for (_, character) in &set.characters {
            if let Some(rows) = glyphs.get(character)
                && let Some(other) = seen.insert(*rows, *character)
                && other != *character
            {
                failures.push(format!(
                    "{}: U+{:04X} {other} and U+{:04X} {character} have the same glyph",
                    set.name,
                    u32::from(other),
                    u32::from(*character)
                ));
            }
        }
    }
    // Listed confusables differ enough.
    for (a, b) in &confusables {
        if let (Some(x), Some(y)) = (glyphs.get(a), glyphs.get(b))
            && distance(x, y) < CONFUSABLE_DISTANCE
        {
            failures.push(format!(
                "U+{:04X} {a} and U+{:04X} {b} differ by fewer than {CONFUSABLE_DISTANCE} dots",
                u32::from(*a),
                u32::from(*b)
            ));
        }
    }
    // Independence from the Bedstead glyphs, for drawn entries.
    let mut audited = 0;
    for (character, entry) in &entries {
        if let (Entry::Drawn { rows, .. }, Some(theirs)) = (entry, reference.get(character))
            && distance(rows, theirs) <= AUDIT_DISTANCE
        {
            if reasons.contains_key(character) {
                audited += 1;
            } else {
                failures.push(format!(
                    "U+{:04X} {character}: too close to the reference glyph; redraw it, or give the reason in {AUDIT}",
                    u32::from(*character)
                ));
            }
        }
    }
    // Coverage.
    let needed = required();
    let missing: Vec<char> = needed.keys().filter(|c| !glyphs.contains_key(c)).copied().collect();
    let drawn = entries.values().filter(|e| matches!(e, Entry::Drawn { .. })).count();
    let copies = entries.values().filter(|e| matches!(e, Entry::Copy(..))).count();
    println!(
        "{} entries ({drawn} drawn, {copies} copies, {} overlays); {} of {} required characters covered; {audited} close matches justified",
        entries.len(),
        entries.len() - drawn - copies,
        needed.len() - missing.len(),
        needed.len()
    );
    if complete {
        failures.extend(release_defaults(root)?);
    }
    if complete && !missing.is_empty() {
        let list: Vec<String> = missing.iter().map(|c| format!("U+{:04X}", u32::from(*c))).collect();
        failures.push(format!("{} required characters have no glyph: {}", missing.len(), list.join(" ")));
    }
    if failures.is_empty() {
        println!("ok");
        Ok(())
    } else {
        for failure in &failures {
            eprintln!("{failure}");
        }
        Err(format!("{} failure(s)", failures.len()))
    }
}

/// Proof sheet geometry: glyphs per row, the size of one dot in pixels, and
/// the cell around a glyph in dots (REQ-RND-010: 6 by 10 for 5 by 9).
const PROOF_COLUMNS: usize = 16;
const PROOF_DOT: usize = 4;
const CELL_WIDTH: usize = COLUMNS + 1;
const CELL_HEIGHT: usize = ROWS + 1;

/// `cargo xtask glyph-proof OUT.png [--compare] [TEXT...]`.
pub fn proof(root: &Path, args: &[String]) -> Result<(), String> {
    let Some((out, texts)) = args.split_first() else {
        return Err("usage: cargo xtask glyph-proof OUT.png [--compare] [TEXT...]".into());
    };
    let entries = parse_original(&read(root, ORIGINAL)?).map_err(|errors| errors.join("\n"))?;
    let glyphs: Vec<(char, Rows)> =
        entries.keys().filter_map(|&c| resolve(&entries, c, 0).map(|rows| (c, rows))).collect();
    // The renderer's placeholder for a character with no glyph (REQ-CHR-004).
    let missing = PLACEHOLDER;
    // With --compare, each glyph is followed by the Bedstead glyph of the
    // same character and a blank cell, for side-by-side review.
    let (compare, texts) = match texts.split_first() {
        Some((flag, rest)) if flag == "--compare" => (true, rest),
        _ => (false, texts),
    };
    let reference = if compare { bedstead(root)? } else { BTreeMap::new() };
    let cells: Vec<Rows> = if compare {
        glyphs.iter().flat_map(|(c, rows)| [*rows, reference.get(c).copied().unwrap_or(missing), [0; ROWS]]).collect()
    } else {
        glyphs.iter().map(|(_, rows)| *rows).collect()
    };
    let per_line = if compare { PROOF_COLUMNS / 2 * 3 } else { PROOF_COLUMNS };
    let mut lines: Vec<Vec<Rows>> = cells.chunks(per_line).map(<[Rows]>::to_vec).collect();
    for text in texts {
        lines.push(Vec::new());
        lines.push(
            text.chars().map(|c| glyphs.iter().find(|(g, _)| *g == c).map_or(missing, |(_, rows)| *rows)).collect(),
        );
    }
    let cells = lines.iter().map(Vec::len).max().unwrap_or(0).max(1);
    let width = cells * CELL_WIDTH * PROOF_DOT;
    let height = lines.len().max(1) * CELL_HEIGHT * PROOF_DOT;
    let ink = |x: usize, y: usize| -> bool {
        let (dot_x, dot_y) = (x / PROOF_DOT, y / PROOF_DOT);
        let (cell, column) = (dot_x / CELL_WIDTH, dot_x % CELL_WIDTH);
        let (line, row) = (dot_y / CELL_HEIGHT, dot_y % CELL_HEIGHT);
        column < COLUMNS
            && row < ROWS
            && lines.get(line).and_then(|l| l.get(cell)).is_some_and(|rows| ink(rows, row, column))
    };
    let palette = [
        neoteletext_image::palette::Rgba { r: 0xF0, g: 0xF0, b: 0xE8, a: 0xFF },
        neoteletext_image::palette::Rgba { r: 0x10, g: 0x10, b: 0x10, a: 0xFF },
    ];
    let mut scratch = vec![0u8; 2 * (width + 1)];
    let mut file = fs::File::create(out).map_err(|e| format!("{out}: {e}"))?;
    neoteletext_image::png::write(
        &mut file,
        width,
        height,
        &palette,
        &mut |y, row: &mut [u8]| {
            for (x, pixel) in row.iter_mut().enumerate() {
                *pixel = u8::from(ink(x, y));
            }
        },
        &mut scratch,
    )
    .map_err(|e| format!("{out}: {e:?}"))?;
    println!("{out}: {} glyphs, {} text lines", glyphs.len(), texts.len());
    Ok(())
}

/// The Rust source of the original glyph table: every entry of
/// `original.txt`, copies and overlays resolved, sorted by code point.
pub fn table_source(root: &Path) -> Result<(String, usize), String> {
    let entries = parse_original(&read(root, ORIGINAL)?).map_err(|errors| errors.join("\n"))?;
    let mut out = String::new();
    out.push_str("//! Generated by `cargo xtask glyphs` from original.txt. Do not edit by hand.\n\n");
    out.push_str("use super::GlyphEntry;\n\n");
    out.push_str("/// Where these glyphs come from (REQ-GEN-012, REQ-RND-028).\n");
    out.push_str("pub(super) const PROVENANCE: &str = \"neoteletext original glyphs (decision E.62; MIT licence; see original.txt and docs/glyph-style-guide.md)\";\n\n");
    let mut rows = Vec::new();
    for &character in entries.keys() {
        let glyph = resolve(&entries, character, 0)
            .ok_or(format!("U+{:04X}: refers to a missing entry, or to itself", u32::from(character)))?;
        rows.push((character, glyph));
    }
    let _ = writeln!(out, "pub(super) static GLYPHS: [GlyphEntry; {}] = [", rows.len());
    for (character, glyph) in &rows {
        let hex: Vec<String> = glyph.iter().map(|row| format!("0x{row:02X}")).collect();
        let _ = writeln!(
            out,
            "    GlyphEntry {{ code_point: 0x{:04X}, rows: [{}] }},",
            u32::from(*character),
            hex.join(", ")
        );
    }
    out.push_str("];\n");
    Ok((out, rows.len()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rows(text: &str) -> Rows {
        let mut out = [0u8; ROWS];
        for (row, line) in out.iter_mut().zip(text.split_whitespace()) {
            *row = line.chars().fold(0, |acc, c| (acc << 1) | u8::from(c == '#'));
        }
        out
    }

    /// The inventory is current: `cargo test` fails when the character
    /// tables change and `required.txt` was not regenerated.
    /// The generated table matches `original.txt`: run `cargo xtask glyphs`
    /// after changing it.
    #[test]
    fn original_table_is_current() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let stored = fs::read_to_string(root.join(TABLE)).unwrap_or_default();
        assert_eq!(stored, table_source(&root).map(|(text, _)| text).unwrap_or_default(), "run `cargo xtask glyphs`");
    }

    #[test]
    fn required_list_is_current() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let stored = fs::read_to_string(root.join(REQUIRED)).unwrap_or_default();
        assert_eq!(stored, required_text(), "run `cargo xtask glyph-inventory`");
    }

    #[test]
    fn parses_the_three_kinds_and_resolves_them() {
        let text = "U+0061 drawn\n.....\n.....\n.###.\n....#\n.####\n#...#\n.####\n.....\n.....\n\n\
                    U+00B4 drawn\n...#.\n..#..\n.....\n.....\n.....\n.....\n.....\n.....\n.....\n\n\
                    U+0430 copy U+0061\nU+00E1 overlay U+0061 U+00B4 dots\n";
        let entries = parse_original(text).unwrap_or_default();
        assert_eq!(entries.len(), 4);
        assert_eq!(resolve(&entries, 'а', 0), resolve(&entries, 'a', 0));
        let composed = resolve(&entries, 'á', 0).unwrap_or_default();
        assert_eq!(composed[0], 0b00010);
        assert_eq!(composed[2], 0b01110);
    }

    #[test]
    fn format_errors_are_reported() {
        assert!(parse_original("U+0061 drawn\n.....\n").is_err());
        assert!(
            parse_original("U+0061 drawn\n....x\n.....\n.....\n.....\n.....\n.....\n.....\n.....\n.....\n").is_err()
        );
        assert!(parse_original("U+0061 drawn shiny\n").is_err());
        assert!(parse_original("U+0061 copy U+0062\nU+0061 copy U+0063\n").is_err());
    }

    #[test]
    fn a_reference_cycle_does_not_resolve() {
        let entries = parse_original("U+0061 copy U+0062\nU+0062 copy U+0061\n").unwrap_or_default();
        assert_eq!(resolve(&entries, 'a', 0), None);
    }

    #[test]
    fn well_formedness_rules() {
        let none = BTreeSet::new();
        let descender: BTreeSet<String> = ["descender".to_string()].into();
        let tail = rows("..... ..... .###. #...# #...# #...# .#### ....# .###.");
        assert_eq!(well_formed('g', &tail, &none), ["U+0067 g: ink in rows 7 to 8 needs the `descender` tag"]);
        assert_eq!(well_formed('g', &tail, &descender), Vec::<String>::new());
        let dotted = rows("..#.. ..... .##.. ..#.. ..#.. ..#.. .###. ..... .....");
        assert_eq!(well_formed('i', &dotted, &none), ["U+0069 i: an isolated dot needs the `dots` tag"]);
        assert_eq!(
            well_formed('x', &[0; ROWS], &none),
            ["U+0078 x: empty glyph", "U+0078 x: a letter stands on the baseline (row 6), or is tagged `raised`"]
        );
        assert_eq!(well_formed(' ', &[0; ROWS], &none), Vec::<String>::new());
        let floating = rows("##### #...# ##### ..... ..... ..... ..... ..... .....");
        assert_eq!(
            well_formed('a', &floating, &none),
            ["U+0061 a: a letter stands on the baseline (row 6), or is tagged `raised`"]
        );
    }

    #[test]
    fn distance_counts_dots() {
        assert_eq!(distance(&rows("#...."), &rows(".#...")), 2);
        assert_eq!(distance(&rows("#####"), &rows("#####")), 0);
    }
}
