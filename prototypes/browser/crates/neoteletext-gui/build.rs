//! Embeds the complete 12 x 10 fonts of the owner's font tree in the
//! browser, for testing (owner, 14 October 2026). The fonts are never part
//! of this repository: they are read at build time from the tree's list,
//! `catalog/complete-fonts.tsv` (every font that conforms for all 24
//! character sets), and compiled in as glyph tables, so the program parses
//! no font at run time (REQ-FNT-003).
//!
//! The tree is `$NEOTELETEXT_FONT_TREE`, or
//! `~/devel/teletext-reference/teletext-fonts`. Fonts under an open licence
//! are always embedded; the others only with the `nonfree-fonts` feature
//! (on by default). Without the tree the browser builds with Bedstead alone.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The cell the browser loads fonts in (REQ-FNT-002).
const WIDTH: usize = 12;
const HEIGHT: usize = 10;
/// The list's columns: `font_id`, `title`, `licence_class`, `file`, `sha256`.
const COLUMNS: usize = 5;
/// The licence class of fonts embedded without the `nonfree-fonts` feature.
const OPEN: &str = "open";

fn tree() -> Option<PathBuf> {
    if let Some(path) = std::env::var_os("NEOTELETEXT_FONT_TREE") {
        return Some(PathBuf::from(path));
    }
    std::env::var_os("HOME").map(|home| PathBuf::from(home).join("devel/teletext-reference/teletext-fonts"))
}

/// The glyphs of a 12 x 10 BDF file: (code point, ten rows of 12 bits).
fn read_bdf(path: &Path) -> Result<Vec<(u32, [u16; HEIGHT])>, String> {
    let text = std::fs::read_to_string(path).map_err(|error| format!("{}: {error}", path.display()))?;
    let mut glyphs = Vec::new();
    let mut code: Option<u32> = None;
    let mut rows: Option<Vec<u16>> = None;
    for line in text.lines() {
        let mut words = line.split_whitespace();
        match words.next() {
            Some("FONTBOUNDINGBOX") => {
                let size: Vec<usize> = words.take(2).filter_map(|word| word.parse().ok()).collect();
                if size != [WIDTH, HEIGHT] {
                    return Err(format!("{} is not {WIDTH} x {HEIGHT}", path.display()));
                }
            }
            Some("ENCODING") => code = words.next().and_then(|word| word.parse().ok()),
            Some("BITMAP") => rows = Some(Vec::new()),
            Some("ENDCHAR") => {
                if let (Some(code_point), Some(found)) = (code.take(), rows.take()) {
                    let mut cell = [0u16; HEIGHT];
                    for (slot, row) in cell.iter_mut().zip(&found) {
                        *slot = *row;
                    }
                    glyphs.push((code_point, cell));
                }
            }
            Some(word) if rows.is_some() => {
                // A 12-pixel row is written as four hexadecimal digits, the
                // last four bits padding.
                let value = u16::from_str_radix(word, 16).map_err(|_| format!("{}: bad row {word}", path.display()))?;
                if let Some(found) = rows.as_mut() {
                    found.push(value >> 4);
                }
            }
            _ => {}
        }
    }
    Ok(glyphs)
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=NEOTELETEXT_FONT_TREE");
    let nonfree = std::env::var_os("CARGO_FEATURE_NONFREE_FONTS").is_some();
    let mut out = String::from("// Generated by build.rs from the font tree's catalog/complete-fonts.tsv.\n");
    out.push_str("/// The embedded fonts, open ones first.\npub static EMBEDDED: &[EmbeddedFont] = &[\n");
    let list = tree().map(|tree| (tree.join("catalog/complete-fonts.tsv"), tree));
    match list {
        Some((list, tree)) if list.exists() => {
            println!("cargo:rerun-if-changed={}", list.display());
            let text = std::fs::read_to_string(&list).unwrap_or_default();
            for line in text.lines().skip(1) {
                let fields: Vec<&str> = line.split('\t').collect();
                if fields.len() != COLUMNS {
                    continue;
                }
                let (id, title, licence, file) = (fields[0], fields[1], fields[2], fields[3]);
                let free = licence == OPEN;
                if !free && !nonfree {
                    continue;
                }
                let path = tree.join(file);
                println!("cargo:rerun-if-changed={}", path.display());
                let glyphs = match read_bdf(&path) {
                    Ok(glyphs) => glyphs,
                    Err(error) => {
                        println!("cargo:warning=skipped {id}: {error}");
                        continue;
                    }
                };
                let _ = writeln!(out, "    EmbeddedFont {{ id: {id:?}, title: {title:?}, free: {free}, glyphs: &[");
                for (code_point, rows) in glyphs {
                    let rows: Vec<String> = rows.iter().map(|row| format!("{row:#05x}")).collect();
                    let _ = writeln!(out, "        FontGlyph {{ code_point: {code_point:#x}, rows: [{}] }},", rows.join(", "));
                }
                out.push_str("    ] },\n");
            }
        }
        _ => println!("cargo:warning=no font tree (set NEOTELETEXT_FONT_TREE): the browser has Bedstead alone"),
    }
    out.push_str("];\n");
    let target = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("embedded_fonts.rs");
    if let Err(error) = std::fs::write(&target, out) {
        println!("cargo:warning=could not write {}: {error}", target.display());
    }
}
