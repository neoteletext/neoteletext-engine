#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_frozen() {
        // The functional codes from 128 follow this order (REQ-INT-105).
        assert_eq!(KEY_NAMES.first(), Some(&"Unidentified"));
        assert_eq!(KEY_NAMES.iter().position(|name| *name == "Enter"), Some(15));
        assert_eq!(KEY_NAMES.iter().position(|name| *name == "ColorF0Red"), Some(134));
        assert_eq!(KEY_NAMES.len(), 168);
    }
}
